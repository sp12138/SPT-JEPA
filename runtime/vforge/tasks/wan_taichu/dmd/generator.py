"""Wan Taichu implementation of the generic DMD generator adapter."""

from __future__ import annotations

from collections.abc import Iterator
from contextlib import contextmanager
from dataclasses import dataclass

import torch
import torch.nn as nn

from vforge.algorithms.dmd.model import (
    DmdGeneratorAdapter,
    DmdNoiseLevel,
    DmdRolloutBlock,
    LatentBundle,
    PreparedDmdBatch,
)
from vforge.models.causal import CausalKVCache, IncrementalKVTransformer
from vforge.models.wan_taichu.inference.causal import build_causal_block_layout
from vforge.models.wan_taichu.inference.incremental_kv import (
    build_incremental_kv_executor,
)
from vforge.tasks.wan_taichu.dmd.inputs import WanDmdInputs, wan_dmd_token_timesteps


@dataclass(frozen=True)
class _WanFrameRange:
    """Half-open latent-frame range generated by one Wan block."""

    start: int
    stop: int

    def __post_init__(self) -> None:
        if self.start < 0 or self.stop <= self.start:
            raise ValueError(f"invalid Wan frame range [{self.start}, {self.stop})")


@dataclass(frozen=True)
class _WanExpert:
    """One expert's incremental executor paired with its own KV cache."""

    executor: IncrementalKVTransformer
    kv_cache: CausalKVCache


@dataclass
class _WanRolloutState:
    """Per-expert executors and caches plus the absolute RoPE for one rollout.

    A14B routes every denoising step to one of two experts and each expert must
    read the K/V it wrote itself: the two towers are independent networks whose
    representations are not interchangeable, so a shared cache would have the
    low-noise steps attend to high-noise K/V. Single-expert variants keep one
    entry and behave exactly as before.
    """

    experts: tuple[_WanExpert, ...]
    boundary: float | None
    full_rotary_emb: tuple[torch.Tensor, torch.Tensor]
    patch_size: tuple[int, int, int]

    def route(self, timestep: torch.Tensor) -> _WanExpert:
        if len(self.experts) == 1:
            return self.experts[0]
        assert self.boundary is not None
        level = _routing_timestep(timestep)
        # ``t >= boundary`` picks the high-noise expert, which is the order
        # ``cache_transformers`` returns and the same comparison the model's own
        # ``select_transformer`` makes.
        return self.experts[0] if level >= self.boundary else self.experts[1]


class WanDmdGeneratorAdapter(DmdGeneratorAdapter):
    """Translate frame-first DMD values into Wan incremental-KV forwards."""

    def __init__(
        self,
        *,
        frame_per_block: int,
        first_frame_own_block: bool = True,
        first_frame_inpaint: bool = True,
        usp_size: int = 1,
    ) -> None:
        if frame_per_block < 1:
            raise ValueError("frame_per_block must be positive")
        self.frame_per_block = int(frame_per_block)
        self.first_frame_own_block = bool(first_frame_own_block)
        self.first_frame_inpaint = bool(first_frame_inpaint)
        self.usp_size = int(usp_size)

    @contextmanager
    def open_rollout_context(
        self,
        generator: nn.Module,
        batch: PreparedDmdBatch[WanDmdInputs],
    ) -> Iterator[_WanRolloutState]:
        towers = _rollout_transformers(generator)
        executors = tuple(
            build_incremental_kv_executor(tower, usp_size=self.usp_size) for tower in towers
        )
        clean_channel_first = batch.clean["latent"].permute(0, 2, 1, 3, 4)
        full_input = torch.cat(
            (clean_channel_first, batch.model_inputs.condition_latents),
            dim=1,
        )
        # The experts share one architecture, so RoPE and the patch grid are
        # common; only the weights and therefore the K/V differ.
        full_rotary_emb = executors[0].full_clip_rotary_emb(full_input)
        p_t, p_h, p_w = (int(value) for value in towers[0].config.patch_size)
        _, _, frames, height, width = full_input.shape
        num_cache_tokens = (frames // p_t) * (height // p_h) * (width // p_w)
        experts = tuple(
            _WanExpert(
                executor=executor,
                kv_cache=executor.init_kv_cache(
                    batch_size=full_input.shape[0],
                    num_cache_tokens=num_cache_tokens,
                    device=full_input.device,
                    dtype=full_input.dtype,
                ),
            )
            for executor in executors
        )
        yield _WanRolloutState(
            experts=experts,
            boundary=_expert_boundary(generator) if len(experts) > 1 else None,
            full_rotary_emb=full_rotary_emb,
            patch_size=(p_t, p_h, p_w),
        )

    def block_layout(
        self,
        batch: PreparedDmdBatch[WanDmdInputs],
        initial_noise: LatentBundle,
    ) -> tuple[DmdRolloutBlock[_WanFrameRange], ...]:
        latent = initial_noise["latent"]
        if latent.shape != batch.clean["latent"].shape:
            raise ValueError("Wan initial noise must match the clean latent shape")
        blocks = []
        for start, stop in build_causal_block_layout(
            latent.shape[1],
            frame_per_block=self.frame_per_block,
            first_frame_own_block=self.first_frame_own_block,
        ):
            # Only the TI2V layout anchors: its first block is the in-painted
            # reference frame, so it starts from the clean latent instead of
            # noise. A14B carries the reference frame in y, which leaves every
            # block an ordinary noisy one.
            is_anchor = self.first_frame_inpaint and start == 0
            blocks.append(
                DmdRolloutBlock(
                    selection=_WanFrameRange(start, stop),
                    initial_value={
                        "latent": (
                            batch.model_inputs.first_frame_latents.permute(0, 2, 1, 3, 4)
                            if is_anchor
                            else latent[:, start:stop]
                        )
                    },
                    is_anchor=is_anchor,
                )
            )
        return tuple(blocks)

    def denoise_block(
        self,
        generator: nn.Module,
        noisy_block: LatentBundle,
        selection: _WanFrameRange,
        noise_level: DmdNoiseLevel[torch.Tensor],
        batch: PreparedDmdBatch[WanDmdInputs],
        context: _WanRolloutState,
    ) -> dict[str, torch.Tensor]:
        del generator
        noisy = noisy_block["latent"]
        model_input = _model_input(noisy, selection, batch)
        timestep = wan_dmd_token_timesteps(
            noise_level.model_timestep,
            model_input,
            context.patch_size,
            frame_range=(selection.start, selection.stop),
        )
        expert = context.route(noise_level.model_timestep)
        velocity = expert.executor.forward_kv_block(
            model_input,
            timestep,
            batch.model_inputs.prompt_embeds,
            kv_cache=expert.kv_cache,
            full_rotary_emb=context.full_rotary_emb,
            kv_write_start=expert.kv_cache.committed_tokens,
            commit_kv=False,
        )
        velocity = velocity[:, : noisy.shape[2]].permute(0, 2, 1, 3, 4)
        sigma = noise_level.sigmas["latent"]
        if sigma.ndim >= 2 and sigma.shape[1] >= selection.stop:
            sigma = sigma[:, selection.start : selection.stop]
        # float64 for the whole conversion, rounded once at the end. Doing
        # ``sigma * velocity`` in the latent's bf16 throws away bits that the
        # subtraction then preserves, which is a visible shift in the rollout.
        x0 = noisy.double() - sigma.to(noisy.device).double() * velocity.double()
        return {"latent": x0.to(velocity.dtype)}

    def commit_block(
        self,
        generator: nn.Module,
        selection: _WanFrameRange,
        context_value: LatentBundle,
        context_noise_level: DmdNoiseLevel[torch.Tensor],
        batch: PreparedDmdBatch[WanDmdInputs],
        context: _WanRolloutState,
    ) -> None:
        del generator
        value = context_value["latent"]
        model_input = _model_input(value, selection, batch)
        timestep = wan_dmd_token_timesteps(
            context_noise_level.model_timestep,
            model_input,
            context.patch_size,
            frame_range=(selection.start, selection.stop),
        )
        # Every expert's history has to stay complete: the next block may route
        # either way, and an expert can only read K/V it wrote itself. So each
        # one encodes this block's context under its own weights into its own
        # cache, high-noise first.
        for expert in context.experts:
            expert.executor.forward_kv_block(
                model_input,
                timestep,
                batch.model_inputs.prompt_embeds,
                kv_cache=expert.kv_cache,
                full_rotary_emb=context.full_rotary_emb,
                kv_write_start=expert.kv_cache.committed_tokens,
                commit_kv=True,
            )

    def concat_blocks(
        self,
        outputs: tuple[tuple[_WanFrameRange, LatentBundle], ...]
        | list[tuple[_WanFrameRange, LatentBundle]],
        batch: PreparedDmdBatch[WanDmdInputs],
    ) -> dict[str, torch.Tensor]:
        del batch
        # Taichu returns rollout latents at the FP32 parameter-storage dtype;
        # subsequent score noise and loss arithmetic use this returned dtype.
        return {"latent": torch.cat([value["latent"] for _range, value in outputs], dim=1).float()}


def _rollout_transformers(module: nn.Module) -> tuple[nn.Module, ...]:
    """Return the towers the rollout drives, high-noise expert first."""

    experts = getattr(module, "cache_transformers", None)
    if callable(experts):
        towers = tuple(experts())
        if towers:
            return towers
    primary = getattr(module, "primary_transformer", None)
    return (primary(),) if callable(primary) else (module,)


def _expert_boundary(module: nn.Module) -> float:
    boundary = getattr(module, "boundary_timestep", None)
    if boundary is None:
        raise ValueError("dual-expert Wan DMD rollout requires a model boundary timestep")
    return float(boundary)


def _routing_timestep(timestep: torch.Tensor) -> float:
    """Reduce a block's timestep to the single rung that picks its expert."""

    values = timestep.reshape(-1)
    if values.numel() == 0:
        raise ValueError("cannot route an empty timestep to a Wan Taichu expert")
    first = values[0]
    if values.numel() > 1 and not bool(torch.all(values == first)):
        raise ValueError(
            "Wan A14B DMD routes a whole block through one expert, so its tokens must "
            "share a timestep; got a block spanning several noise levels"
        )
    return float(first)


def _model_input(
    frame_first: torch.Tensor,
    selection: _WanFrameRange,
    batch: PreparedDmdBatch[WanDmdInputs],
) -> torch.Tensor:
    channel_first = frame_first.permute(0, 2, 1, 3, 4)
    condition = batch.model_inputs.condition_latents[:, :, selection.start : selection.stop]
    return torch.cat((channel_first, condition), dim=1)


__all__ = ["WanDmdGeneratorAdapter"]
