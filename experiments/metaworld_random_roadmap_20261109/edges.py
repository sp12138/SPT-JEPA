def quantized_nll(mean,target,variance):
    """Censored 8-bit Gaussian bin probability, stable even in distant tails."""
    m=mean.double();x=target.double().expand_as(m);s=variance.double().expand_as(m).sqrt();delta=.5/255
    distance=(x-m).abs();hi=(delta-distance)/s;lo=(-delta-distance)/s
    a=torch.special.log_ndtr(hi);b=torch.special.log_ndtr(lo)
    logp=a+torch.log(-torch.expm1(b-a))
    logp=torch.where(x==0,torch.special.log_ndtr((delta-m)/s),logp)
    logp=torch.where(x==1,torch.special.log_ndtr((m-1+delta)/s),logp)
    result=-logp.mean((1,2,3));assert torch.isfinite(result).all() and (result>=-1e-8).all()
    return result.float().clamp_min(0)


@torch.no_grad()
def steer(world,inverse,hidden,current,current_feature,target,target_feature):
    h=hidden;feature=current_feature;first=None;direction=torch.zeros(len(hidden),device=hidden.device,dtype=torch.long)
    for _ in range(HORIZON):
        action=inverse.inverse(torch.cat([feature,target_feature,target_feature-feature],1)).float().clamp(-1,1)
        assert torch.isfinite(action).all()
        if first is None:first=action.clone()
        h=world.parent.advance(h,action,direction);prediction=world.parent.render(h,current);feature=inverse.vision(prediction)
    variance,basis=world.distribution(h);assert basis is None
    return quantized_nll(prediction,target,variance),quantized_nll(current,target,variance),first


