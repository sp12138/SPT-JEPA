def audit():
    # Actual double-precision reference for ordinary interior bins and censoring.
    torch.set_num_threads(2);means=torch.tensor([.3,.6,.01,.99],dtype=torch.float64).reshape(4,1,1,1)
    targets=torch.tensor([.31,.59,0.,1.],dtype=torch.float64).reshape(4,1,1,1);v=torch.full_like(means,.05**2)
    normal=torch.distributions.Normal(means,.05);delta=.5/255
    prob=normal.cdf(targets+delta)-normal.cdf(targets-delta)
    prob[2]=normal.cdf(targets+delta)[2];prob[3]=(1-normal.cdf(targets-delta))[3]
    reference=-prob.log().flatten();actual=quantized_nll(means,targets,v).double();error=float((reference-actual).abs().max());assert error<1e-5
    tails=quantized_nll(torch.ones(1,3,4,4)*.99,torch.ones(1,3,4,4)*.01,torch.ones(1,3,4,4)*(1/255)**2/12)
    assert torch.isfinite(tails).all() and float(tails)>1000
    save(ROOT/'EDGE_MATH_AUDIT.json',dict(passed=True,utc=now(),quantized_Gaussian_FP64_reference_error=error,
        far_tail_finite=True,optimizer_updates=0,physics_steps=0,helper_sha256=sha(__file__)))


